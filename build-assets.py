"""Bundle the animation binaries for reliable local and hosted previews."""

import base64
import json
from pathlib import Path


root = Path(__file__).resolve().parent
wasm = base64.b64encode((root / "ani.wasm").read_bytes()).decode("ascii")
data = base64.b64encode((root / "anim_data.bin").read_bytes()).decode("ascii")

source = f"""// Generated by build-assets.py from ani.wasm and anim_data.bin.
(function () {{
  const encoded = {{ wasm: {json.dumps(wasm)}, data: {json.dumps(data)} }};
  window.AnimationAssets = {{
    decode(name) {{
      const binary = atob(encoded[name]);
      const bytes = new Uint8Array(binary.length);
      for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
      return bytes;
    }}
  }};
}})();
"""

(root / "animation-assets.js").write_text(source, encoding="utf-8")
